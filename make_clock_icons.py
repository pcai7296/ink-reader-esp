def rows_of(art):
    assert len(art) == SIZE, "icon must have %d rows" % SIZE
    out = []
    for line in art:
        assert len(line) == SIZE, "icon row must be %d wide: %r" % (SIZE, line)
        hi = lo = 0
        for x, ch in enumerate(line):
            if ch == '#':
                if x < 8:
                    hi |= 0x80 >> x
                else:
                    lo |= 0x80 >> (x - 8)
        out.append((hi, lo))
    return out


def emit_header():
    print("// clock_icons.h — 16x16 时钟页/状态栏图标 (由 make_clock_icons.py 生成, 勿手改)")
    print("// 顺序: " + " ".join("%d=%s" % (i, cn) for i, (_, cn, _) in enumerate(ICONS)))
    print("#pragma once")
    print("#include <Arduino.h>")
    print("")
    print("#define CK_ICON_COUNT %d" % len(ICONS))
    for i, (nm, _, _) in enumerate(ICONS):
        print("#define CK_ICON_%s %d" % (nm, i))
    print("")
    print("static const uint8_t ckIcons[CK_ICON_COUNT][%d] PROGMEM = {" % (SIZE * 2))
    for i, (nm, cn, art) in enumerate(ICONS):
        body = ", ".join("0x%02X,0x%02X" % (hi, lo) for hi, lo in rows_of(art))
        print("  { %s },   // %d %s (%s)" % (body, i, nm, cn))
    print("};")


def emit_preview(path):
    from PIL import Image, ImageDraw
    scale = 8
    pad = 6
    cols = 7
    rows = (len(ICONS) + cols - 1) // cols
    cell = SIZE * scale + pad
    img = Image.new("RGB", (cols * cell + pad, rows * cell + pad + 20), (255, 255, 255))
    d = ImageDraw.Draw(img)
    for i, (nm, cn, art) in enumerate(ICONS):
        cx = pad + (i % cols) * cell
        cy = pad + (i // cols) * cell
        for y, line in enumerate(art):
            for x, ch in enumerate(line):
                if ch == '#':
                    d.rectangle([cx + x * scale, cy + y * scale,
                                 cx + (x + 1) * scale - 1, cy + (y + 1) * scale - 1],
                                fill=(0, 0, 0))
        d.text((cx, cy + SIZE * scale + 2), "%d %s" % (i, nm), fill=(0, 0, 0))
    img.save(path)
    print("preview -> %s (%d icons, x%d)" % (path, len(ICONS), scale))


